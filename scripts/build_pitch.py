"""Generate the pitch material and the draft paperwork (BLUEPRINT.md Sections 12.2, 16, 18).

Usage (repository root): PYTHONPATH=backend:. python -m scripts.build_pitch   (or `make docs`)
Writes docs/pitch/*.md (demo script, pitch outline, judge questions) and docs/drafts/*.md (logic
chain, Safe Order terms, interview consent note, team agreement outline, regulatory note, questions
for the organisers). Every number comes from reports/*.json or config/config.yaml, and anything not
measured says so. The drafts are NOT legal advice and are not upay policy: people must review them.
"""

from typing import Any

from app.config import load_config
from scripts.build_docs import NOT_MEASURED, REPO, load, num, pct, table

DOCS = REPO / "docs"
DRAFT = (
    "> **DRAFT for the team to review. Not legal advice, not an upay policy, not a product.**\n"
    "> Synthetic data, simulated money, not validated on real data.\n"
    "> Generated by `scripts/build_pitch.py`; edit the script (or copy the text out) rather than this file.\n"
)


class Facts:
    """Every number the pitch may quote, read from the reports (``NOT_MEASURED`` when missing)."""

    def __init__(self, cfg: dict[str, Any]) -> None:
        self.cfg = cfg
        trust, dispute = load("trust_eval.json"), load("dispute_eval_baseline.json")
        inj = load("injection_eval.json")
        self.trust, self.dispute, self.inj = trust, dispute, inj
        self.hold = cfg["rules"]["hold_period_hours"]
        self.deadline = cfg["rules"]["seller_response_deadline_hours"]
        self.limited_days = cfg["rules"]["trust"]["limited_history_max_age_days"]
        self.limited_orders = cfg["rules"]["trust"]["limited_history_min_orders"]
        self.high_amount = cfg["rules"]["routing"]["high_amount_bdt"]
        self.min_prob = cfg["rules"]["routing"]["min_class_probability"]
        if trust:
            test = trust["test_v2"]["noisy_label"]
            self.fpr = trust["target_false_positive_rate"]
            self.t_recall = pct(test["model"]["recall_at_target_fpr"]["recall"], 0)
            self.t_base_recall = pct(
                test["age_score_baseline"]["recall_at_target_fpr"]["recall"], 0
            )
            self.t_rule_recall = pct(test["age_rule_baseline"]["recall"], 0)
            self.t_pr = num(test["model"]["pr_auc"], 2)
            self.t_base_pr = num(test["age_score_baseline"]["pr_auc"], 2)
            pol = trust["fairness_and_policy_v2"]
            self.literal_recall = pct(pol["blueprint_literal"]["recall_high_risk_overall"], 0)
            self.override_recall = pct(pol["override_default"]["recall_high_risk_overall"], 0)
            self.new_fp = pct(pol["override_default"]["false_positive_rate"]["honest_new"], 1)
            self.latency = f"{trust['latency']['p95_ms']:.1f} ms"
        else:
            self.fpr = self.t_recall = self.t_base_recall = self.t_rule_recall = NOT_MEASURED
            self.t_pr = self.t_base_pr = self.literal_recall = self.override_recall = NOT_MEASURED
            self.new_fp = self.latency = NOT_MEASURED
        if dispute:
            t1, t2 = dispute["splits"]["test1"], dispute["splits"]["test2"]
            self.d_f1_1, self.d_f1_2 = num(t1["macro_f1"], 2), num(t2["macro_f1"], 2)
            self.d_story_2 = num(t2["story_level"]["macro_f1"], 2)
            self.d_stories_2 = str(t2["distinct_stories"])
            self.d_n_2 = str(t2["n"])
            self.wr_1, self.wr_2 = pct(t1["wrong_refund_rate"]), pct(t2["wrong_refund_rate"])
            self.wj_1, self.wj_2 = pct(t1["wrong_rejection_rate"]), pct(t2["wrong_rejection_rate"])
            route = dispute["routing"]["test1"]
            self.fast_share = pct(route["fast_lane_share"], 0)
            self.fast_acc = pct(route["fast_lane_accuracy"], 0)
            self.fast_wr = str(route["fast_lane_wrong_refunds"])
            self.human_share = pct(route["human_review_share"], 0)
            self.d_latency = f"{dispute['latency']['p95_ms']:.1f} ms"
        else:
            self.d_f1_1 = self.d_f1_2 = self.d_story_2 = self.d_stories_2 = self.d_n_2 = (
                NOT_MEASURED
            )
            self.wr_1 = self.wr_2 = self.wj_1 = self.wj_2 = NOT_MEASURED
            self.fast_share = self.fast_acc = self.fast_wr = self.human_share = NOT_MEASURED
            self.d_latency = NOT_MEASURED
        if inj:
            self.inj_dev = f"{inj['screen']['detected']} of {inj['screen']['injection_phrases']}"
            self.inj_new = (
                f"{inj['untuned_screen']['detected']} of {inj['untuned_screen']['phrases']}"
            )
        else:
            self.inj_dev = self.inj_new = NOT_MEASURED
        cls = (dispute or {}).get("injection")
        self.inj_cases = (
            f"{cls['screen_detected']} of {cls['n']}" if cls and cls.get("n") else NOT_MEASURED
        )


