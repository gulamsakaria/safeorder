"""Generate the documentation set (BLUEPRINT.md Section 16) with numbers read from reports/*.json.

Usage (repository root): PYTHONPATH=backend:. python -m scripts.build_docs   (or `make docs`)
Writes into docs/: model_card_trust.md, dataset_card_synthetic_sellers.md, evaluation_protocol.md,
responsible_ai.md, licence_register.md and README.md (an index with the status of every document).

Every number comes from a report file; the prose says what the report cannot say. Run
`make eval` first. Do not edit the generated files by hand.
"""

import json
from importlib import metadata
