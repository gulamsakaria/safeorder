def main() -> None:
    f = Facts(load_config())
    outputs = {
        "pitch/demo_script.md": demo_script(f),
        "pitch/pitch_outline.md": pitch_outline(f),
        "pitch/judge_questions.md": judge_questions(f),
        "drafts/logic_chain.md": logic_chain(f),
        "drafts/safe_order_terms.md": terms(f),
        "drafts/interview_consent_note.md": consent_note(),
        "drafts/team_agreement_outline.md": team_agreement(),
        "drafts/regulatory_note.md": regulatory_note(),
        "drafts/organiser_questions.md": organiser_questions(),
    }
    for name, text in outputs.items():
        path = DOCS / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote docs/{name}")


if __name__ == "__main__":
    main()
