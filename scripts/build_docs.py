SKIP_LINE = 80


def python_licence(name: str) -> tuple[str, str]:
    try:
        meta = metadata.metadata(name)
    except metadata.PackageNotFoundError:
        return "not installed", "-"
    version = meta.get("Version", "?")
    expression = meta.get("License-Expression")
    if expression:
        return version, expression
    classifiers = [
        c.split("::")[-1].strip()
        for c in meta.get_all("Classifier", [])
        if c.startswith("License ::")
    ]
    if classifiers:
        return version, "; ".join(classifiers)
    text = (meta.get("License") or "").strip().splitlines()
    if text and len(text[0]) <= SKIP_LINE:
        return version, text[0]
    return version, "see package metadata (not summarised by the script)"


def licence_register() -> str:
    requirements = [
        line.strip()
        for line in (REPO / "requirements.txt").read_text().splitlines()
        if line.strip()
    ]
    py_rows = [[f"`{n}`", *python_licence(n)] for n in requirements]
    package = json.loads((REPO / "frontend" / "package.json").read_text(encoding="utf-8"))
    js_rows = []
    for section in ("dependencies", "devDependencies"):
        for name, wanted in sorted(package[section].items()):
            installed = REPO / "frontend" / "node_modules" / name / "package.json"
            if installed.exists():
                info = json.loads(installed.read_text(encoding="utf-8"))
                licence = info.get("license")
