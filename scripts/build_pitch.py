def regulatory_note() -> str:
    return f"""# Draft: regulatory note on held payments

{DRAFT}
**What the prototype does.** It simulates holding a buyer's payment until delivery and then releasing it
or refunding it. No real money moves; the wallet is a sandbox ledger.

**Why it needs care.** In a real system, holding customer funds between two parties may count as a
regulated payment activity (for example escrow-like services), and may need the approval of the financial
regulator and of the payment provider. Rules about mobile financial services, customer data protection,
and dispute handling also apply.

**What we claim.** Safe Order is presented as a *future feature governed by upay*, simulated here. We do
not claim it can be launched by us, and we do not claim that any rule in the prototype is an upay policy.

**What we have not done.** We have not consulted a lawyer or the regulator and have not read the
current regulations. A legal adviser must check this before the pitch if it is going to be said as more
than "simulated".

**Questions to take to the organisers or an adviser:** does a held-payment concept need to be reviewed
for the event; which approvals a real pilot would need; who is the right contact at upay.
"""


