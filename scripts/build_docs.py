def main() -> None:
    cfg = load_config()
    outputs = {
        "model_card_trust.md": model_card(cfg),
        "dataset_card_synthetic_sellers.md": dataset_card(),
        "evaluation_protocol.md": evaluation_protocol(cfg),
        "responsible_ai.md": responsible_ai(cfg),
        "licence_register.md": licence_register(),
    }
