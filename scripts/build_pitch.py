def terms(f: Facts) -> str:
    return f"""# Draft: Safe Order terms and dispute policy

{DRAFT}
Real terms belong to upay and its legal advisers. This draft only records the rules the prototype
simulates, so the team can discuss them. Every value is a starting value from `config/config.yaml`.

1. **Safe Order.** The buyer pays into a hold, not to the seller. The seller sees that payment is
   held; the money is released after delivery and the hold period, or refunded after a decision.
2. **Hold period.** {f.hold} hours after delivery is confirmed (by the courier, or by the buyer entering
   the delivery code).
3. **Dispatch deadline.** If the seller does not dispatch within {f.cfg["rules"]["dispatch_deadline_hours"]} hours, the order
   becomes disputable.
4. **Who can dispute.** Either party's order, within the hold; the buyer files a report with a
   description of the problem; the seller may reply within {f.deadline} hours.
5. **Evidence accepted.** Text descriptions of proof in the prototype (courier receipts, tracking numbers,
   chat screenshots described in words). Photos and videos are not analysed by the system.
6. **Who decides.** An analyst decides every dispute and must write a reason. The system only
   suggests. Cases with any warning flag, low confidence, an amount above {f.high_amount} taka, an
   injection attempt or insufficient evidence always go to a human; the "fast lane" only pre-fills a
   confirmation, never a refund.
7. **Possible decisions.** Refund the buyer; reject the claim (money to the seller); ask for more
   evidence (the response window restarts); escalate for senior review.
8. **Appeals.** One appeal per party, which goes to the escalated queue.
9. **Seller score.** A new decision updates the seller's record; sellers with little history (under
   {f.limited_days} days or {f.limited_orders} orders) see a neutral "limited history" label instead of a score.
10. **Records.** Every state change and decision is kept in an append-only audit log.

**Open questions for upay and a lawyer:** who may hold customer funds and under which approval;
liability when a courier loses a parcel; how long records are kept; how appeals are resolved.
"""


