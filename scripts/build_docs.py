NOT_MEASURED = "not measured"


def load(name: str) -> dict[str, Any] | None:
    path = REPO / "reports" / name
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def pct(value: float | None, digits: int = 1) -> str:
    return NOT_MEASURED if value is None else f"{value * 100:.{digits}f}%"


def num(value: float | None, digits: int = 3) -> str:
    return NOT_MEASURED if value is None else f"{value:.{digits}f}"


def get(node: Any, *path: str) -> Any:
    for key in path:
        if not isinstance(node, dict) or key not in node:
            return None
        node = node[key]
    return node


def plain(counts: dict[str, Any]) -> str:
    return ", ".join(f"{k}: {v}" for k, v in counts.items())


def table(head: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


